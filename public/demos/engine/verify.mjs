import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';

const root = dirname(fileURLToPath(import.meta.url));
const requireOriginal = createRequire(join(process.argv[2], 'package.json'));
const { chromium } = requireOriginal('@playwright/test');
const out = join(root, 'qa');
await mkdir(out, { recursive: true });
const report = { passed: false, errors: [], failed: [], missing: [], checks: [], scope: 'Actual reused EngineThree geometry, synthetic crank angle and rpm, no native engine or audio' };
const browser = await chromium.launch({ headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const requests = [];
  page.on('request', request => requests.push(request.url()));
  page.on('pageerror', error => report.errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') report.errors.push(message.text()); });
  page.on('requestfailed', request => report.failed.push(request.url()));
  page.on('response', response => { if (response.status() >= 400) report.missing.push({ url: response.url(), status: response.status() }); });
  await page.goto('http://127.0.0.1:5174/demos/engine/index.html');
  assert.equal(await page.locator('canvas').count(), 0);
  assert.equal(requests.some(url => url.endsWith('/engine.js') || url.includes('/models/')), false);
  report.checks.push('No 3D bundle, model download or animation before explicit activation.');
  const started = Date.now();
  await page.locator('#load-engine').click();
  await page.waitForFunction(() => window.engineDemo || document.querySelector('#engine-status')?.textContent === '3D-Ansicht nicht verfügbar', null, { timeout: 150000 });
  assert.equal(await page.evaluate(() => Boolean(window.engineDemo)), true);
  await page.waitForTimeout(500);
  report.initializationMs = Date.now() - started;
  const snapshot = () => page.evaluate(() => { const state = window.engineDemo.snapshot(); return { running: state.running, component: state.component, angle: state.angle, rpm: state.requestedRpm, pistonPositions: state.diagnostics.parts.map(part => part.piston), camera: state.diagnostics.camera.position, geometryCache: document.querySelector('#engine-host').dataset.geometryCache, resources: state.diagnostics.resources, graphics: document.querySelector('#engine-host').dataset.graphics }; });
  const before = await snapshot();
  await page.waitForTimeout(500);
  const moving = await snapshot();
  assert.notDeepEqual(before.pistonPositions, moving.pistonPositions);
  assert.equal(moving.pistonPositions.length, 6);
  report.checks.push('Six original pistons and crank-driven connecting rods change their real 3D poses.');
  await page.locator('#run-engine').click();
  await page.waitForTimeout(300);
  const stopped = await snapshot();
  await page.waitForTimeout(500);
  const still = await snapshot();
  assert.equal(still.angle, stopped.angle);
  assert.deepEqual(still.pistonPositions, stopped.pistonPositions);
  report.checks.push('Stop freezes actual crank angle and all piston poses.');
  await page.locator('#engine-rpm').fill('4000');
  assert.match(await page.locator('#rpm-value').textContent(), /4\.000/);
  await page.locator('#run-engine').click();
  await page.waitForTimeout(500);
  const faster = await snapshot();
  assert.equal(faster.rpm, 4000);
  assert.notDeepEqual(still.pistonPositions, faster.pistonPositions);
  report.checks.push('Rpm input changes the requested rpm and drives the reused moving geometry.');
  const canvas = page.locator('canvas');
  const bounds = await canvas.boundingBox();
  const cameraBefore = faster.camera;
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * .65, bounds.y + bounds.height * .6, { steps: 12 });
  await page.mouse.up();
  await page.waitForTimeout(350);
  assert.notDeepEqual((await snapshot()).camera, cameraBefore);
  report.checks.push('Pointer orbit changes the actual 3D camera.');
  await page.locator('#reset-camera').click();
  await page.locator('#run-engine').click();
  await page.waitForTimeout(350);
  await page.screenshot({ path: join(out, 'desktop-1280.png') });
  await page.locator('#view-piston').click();
  await page.waitForTimeout(350);
  assert.equal((await snapshot()).component, 'piston');
  await page.screenshot({ path: join(out, 'piston-detail-1280.png') });
  await page.locator('#view-section').click();
  await page.setViewportSize({ width: 375, height: 812 });
  await page.waitForTimeout(500);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('#run-engine').isVisible(), true);
  assert.equal(await page.locator('#engine-rpm').isVisible(), true);
  await page.screenshot({ path: join(out, 'mobile-375.png') });
  report.checks.push('Desktop and 375px mobile rendered with no horizontal overflow; real controls remain visible.');
  report.final = await snapshot();
  assert.deepEqual(report.errors, []);
  assert.deepEqual(report.failed, []);
  assert.deepEqual(report.missing, []);
  report.passed = true;
} catch (error) {
  report.failure = String(error.stack || error);
  process.exitCode = 1;
} finally {
  await browser.close();
  await writeFile(join(out, 'report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
}
